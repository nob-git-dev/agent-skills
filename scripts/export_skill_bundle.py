#!/usr/bin/env python3
"""Export one skill folder as (1) a single Markdown file and (2) a zip for chat apps.

Usage:
    python3 scripts/export_skill_bundle.py <skill-name> [--check]

Outputs:
    dist/<skill-name>.md   SKILL.md followed by every reference file, with
                           links to bundled files rewritten to in-document anchors.
    dist/<skill-name>.zip  The skill folder (<skill-name>/SKILL.md, references/, ...)
                           for apps that install skills from an uploaded zip.

The zip is deterministic (fixed timestamps, sorted entries) so --check can
compare bytes. Standard library only.
"""
from pathlib import Path
import argparse
import io
import re
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
FIXED_TIME = (2020, 1, 1, 0, 0, 0)
SKIP_PARTS = {"__pycache__", ".DS_Store"}


def skill_files(folder):
    files = [p for p in sorted(folder.rglob("*")) if p.is_file()
             and not any(part in SKIP_PARTS for part in p.parts)]
    return files


def anchor(rel):
    return "file-" + re.sub(r"[^a-z0-9]+", "-", rel.lower()).strip("-")


def build_markdown(name, folder):
    entry = folder / "SKILL.md"
    refs = [p for p in skill_files(folder) if p.suffix == ".md" and p != entry]
    rels = {p.relative_to(folder).as_posix() for p in refs}

    def relink(text):
        def sub(m):
            label, target = m.group(1), m.group(2)
            return f"[{label}](#{anchor(target)})" if target in rels else m.group(0)
        return re.sub(r"\[([^\]]+)\]\(([^)#\s]+)\)", sub, text)

    out = [f"<!-- generated by scripts/export_skill_bundle.py from skills/{name}/ ; edit the folder, not this file -->",
           f"# {name}（統合版）",
           "",
           "このファイルはスキルのフォルダを1つにまとめたものです。最初の節が指示本体（SKILL.md）、"
           "続く節が必要に応じて読む参照資料です。",
           "",
           f'<a id="{anchor("SKILL.md")}"></a>',
           "## SKILL.md",
           "",
           relink(entry.read_text(encoding="utf-8")).rstrip(),
           ""]
    for p in refs:
        rel = p.relative_to(folder).as_posix()
        out += ["", "---", "", f'<a id="{anchor(rel)}"></a>', f"## {rel}", "",
                relink(p.read_text(encoding="utf-8")).rstrip(), ""]
    return "\n".join(out) + "\n"


def build_zip(name, folder):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in skill_files(folder):
            info = zipfile.ZipInfo(f"{name}/{p.relative_to(folder).as_posix()}", FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, p.read_bytes())
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("skill")
    ap.add_argument("--check", action="store_true", help="fail if dist files are stale")
    args = ap.parse_args()
    folder = ROOT / "skills" / args.skill
    if not (folder / "SKILL.md").is_file():
        sys.exit(f"Not a skill folder: {folder}")
    outputs = {
        ROOT / "dist" / f"{args.skill}.md": build_markdown(args.skill, folder).encode("utf-8"),
        ROOT / "dist" / f"{args.skill}.zip": build_zip(args.skill, folder),
    }
    stale = [p for p, data in outputs.items() if not p.is_file() or p.read_bytes() != data]
    if args.check:
        if stale:
            sys.exit("Stale: " + ", ".join(p.relative_to(ROOT).as_posix() for p in stale))
        print(f"{args.skill} bundle is current.")
        return
    for p, data in outputs.items():
        p.write_bytes(data)
        print(f"Wrote {p.relative_to(ROOT).as_posix()} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
